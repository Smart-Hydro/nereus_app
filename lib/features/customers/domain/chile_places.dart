String foldPlace(String value) {
  const from = 'áéíóúüñÁÉÍÓÚÜÑ';
  const to = 'aeiouunAEIOUUN';
  final buffer = StringBuffer();
  for (final char in value.split('')) {
    final index = from.indexOf(char);
    buffer.write(index < 0 ? char : to[index]);
  }
  return buffer.toString().toLowerCase();
}

ChilePlace? placeForCommune(String commune) {
  final needle = foldPlace(commune.trim());
  if (needle.isEmpty) return null;
  for (final place in chilePlaces) {
    if (foldPlace(place.commune) == needle) return place;
  }
  return null;
}

List<ChilePlace> suggestPlaces(String query, {String? region}) {
  final needle = foldPlace(query.trim());
  final scoped = region == null || region.isEmpty;
  if (needle.length < 2 && scoped) return const [];
  final matches = <ChilePlace>[];
  for (final place in chilePlaces) {
    if (!scoped && place.region != region) continue;
    final haystack = foldPlace(
      '${place.commune} ${place.province} ${place.region}',
    );
    if (needle.isEmpty || haystack.contains(needle)) {
      matches.add(place);
    }
    if (matches.length == 8) break;
  }
  return matches;
}
